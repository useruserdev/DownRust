// SPDX-License-Identifier: GPL-3.0-or-later
// Puts the licence header on the theme files that `astryx theme build` writes.
import fs from 'node:fs';

const FILES = [
  'src/astryx-themes.ts',
  'src/themes/downrust/downrust.css',
  'src/themes/downrust/downrust.css.d.ts',
  'src/themes/downrust/downrust.d.ts',
  'src/themes/downrust/downrust.js',
  'src/themes/downrust/downrust.variants.d.ts',
];

for (const file of FILES) {
  if (!fs.existsSync(file)) continue;
  const css = file.endsWith('.css');
  const spdx = css
    ? '/* SPDX-License-Identifier: GPL-3.0-or-later */'
    : '// SPDX-License-Identifier: GPL-3.0-or-later';
  let text = fs.readFileSync(file, 'utf8');
  text = text
    .replace(/@generated by `astryx theme( build)?`/g, (_, build) => `Built by \`astryx theme${build ?? ''}\``)
    .replace(/Generated by astryx theme build/g, 'Built by astryx theme build');
  if (!text.startsWith(spdx)) text = `${spdx}\n${text}`;
  fs.writeFileSync(file, text);
}
